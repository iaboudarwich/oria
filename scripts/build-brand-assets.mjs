#!/usr/bin/env node
/**
 * Brand-asset extractor (run rarely, by hand, when the brand face changes).
 *
 * The brand face is Newsreader (the wordmark's serif). Rendering it as live
 * <text> would fall back to Georgia on any machine without Newsreader, and
 * shipping the whole font for one mark is wasteful. So we extract the actual
 * Newsreader outlines ONCE into font-independent SVG paths and commit those:
 *
 *   public/brand/monogram.svg   tight "O" path (icon source; rasterized by
 *                               scripts/generate-icons.mjs with sharp only)
 *   public/logo.svg             the "Oria" lockup, square cream field, as a
 *                               path (so it renders identically everywhere)
 *   lib/brand/wordmark-path.ts  the "Oria" path + viewBox for the in-app
 *                               Wordmark component (inlined so it recolors via
 *                               currentColor, no font in the bundle)
 *
 * Requires (dev-only, NOT a build/gate dependency): network access and
 * opentype.js (`npm i --no-save opentype.js`). The downstream icon build
 * (generate-icons.mjs) needs neither: it only rasterizes the committed SVG.
 *
 * Run: npm i --no-save opentype.js && node scripts/build-brand-assets.mjs
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import opentype from "opentype.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const INK = "#0f0f0f";
const CREAM = "#f5f1ea";
// Newsreader, roman, weight 400, the wordmark's optical range.
const CSS_URL =
  "https://fonts.googleapis.com/css2?family=Newsreader:opsz,wght@6..72,400&display=swap";

async function loadFont() {
  const css = await (
    await fetch(CSS_URL, { headers: { "User-Agent": "Mozilla/5.0 (X11; Linux x86_64)" } })
  ).text();
  const m = css.match(/url\((https:[^)]+\.ttf)\)/);
  if (!m) throw new Error("could not find a TTF url in the Google Fonts CSS");
  const buf = Buffer.from(await (await fetch(m[1])).arrayBuffer());
  return opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
}

/** Bounding box of a glyph string laid out at `fontSize`, plus its path data. */
function layout(font, text, fontSize) {
  const path = font.getPath(text, 0, 0, fontSize);
  const bb = path.getBoundingBox();
  return { d: path.toPathData(2), bb };
}

const font = await loadFont();
console.log(`loaded Newsreader (unitsPerEm ${font.unitsPerEm})`);

// ── 1. Monogram "O": tight viewBox around the glyph, ink on transparent. ──────
{
  const { d, bb } = layout(font, "O", 1000);
  const w = +(bb.x2 - bb.x1).toFixed(2);
  const h = +(bb.y2 - bb.y1).toFixed(2);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${bb.x1.toFixed(2)} ${bb.y1.toFixed(2)} ${w} ${h}" width="${w}" height="${h}">
  <path d="${d}" fill="${INK}"/>
</svg>
`;
  writeFileSync(join(ROOT, "public", "brand", "monogram.svg"), svg);
  console.log(`wrote public/brand/monogram.svg  (O ${w.toFixed(0)}x${h.toFixed(0)})`);
}

// ── 2. logo.svg: the "Oria" lockup on a square cream field, centered. ─────────
{
  const SIZE = 1024;
  const FS = 320; // matches the prior wordmark's optical size
  const { d, bb } = layout(font, "Oria", FS);
  const advW = bb.x2 - bb.x1;
  const tx = (SIZE - advW) / 2 - bb.x1; // center horizontally
  const ty = SIZE / 2 - (bb.y1 + bb.y2) / 2; // center on the cap band
  const svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 ${SIZE} ${SIZE}">
  <rect width="${SIZE}" height="${SIZE}" fill="${CREAM}"/>
  <path d="${d}" fill="${INK}" transform="translate(${tx.toFixed(2)} ${ty.toFixed(2)})"/>
</svg>
`;
  writeFileSync(join(ROOT, "public", "logo.svg"), svg);
  console.log("wrote public/logo.svg  (Oria lockup, path-based)");
}

// ── 3. wordmark-path.ts: the "Oria" path for the in-app component. ────────────
{
  const { d, bb } = layout(font, "Oria", 1000);
  const x = bb.x1.toFixed(2);
  const y = bb.y1.toFixed(2);
  const w = (bb.x2 - bb.x1).toFixed(2);
  const h = (bb.y2 - bb.y1).toFixed(2);
  const ts = `// Generated by scripts/build-brand-assets.mjs. Do not edit by hand.
// The Newsreader "Oria" wordmark as a font-independent path so the in-app
// Wordmark renders the real serif everywhere, recolors via currentColor, and
// pulls no font into the bundle.
export const ORIA_VIEWBOX = "${x} ${y} ${w} ${h}";
export const ORIA_PATH =
  "${d}";
`;
  writeFileSync(join(ROOT, "lib", "brand", "wordmark-path.ts"), ts);
  console.log("wrote lib/brand/wordmark-path.ts");
}

console.log("done");
